# ---------- 第一组：数字之间的除法 ----------

# "/" 是除法。
# 关键点：Python 3 里，"/" 的结果永远是小数 float，
# 就算两个整数能整除，结果也会带小数点（比如 4/2 得到 2.0 而不是 2）。
# 这是 Python 3 和旧版本最重要的区别之一。
print(10 / 3)

# "//" 是整除（向下取整）。它把小数部分直接砍掉，结果还是整数。
# 生活例子：10 块钱买 3 块一个的包子，能买几个？用 // 算。
print(10 // 3)

# "%" 是取余（求余数）。
# 生活例子：10 个包子分给 3 个人，分完还剩几个？
print(10 % 3)


# ---------- 第二组：字符串之间的运算 ----------

# 两个字符串用 "+" 连起来。注意：结果还是字符串，不是数字。
# 这就是「类型决定行为」：同一个 + 号，
#   对数字是加法，对字符串是拼接。
print("3" + "3")

# 字符串 * 整数 = 把这个字符串重复若干次。
# 这是 Python 特有的写法，反过来 3 * "3" 结果一样。
print("3" * 3)


# ---------- 第三组：类型转换 ----------

# int("3") 的意思：把字符串 "3" 变成整数 3。
# 为什么需要？因为文件、网页、客户系统传过来的数据，默认全是字符串。
# 不转换就直接参与计算，会得到你意想不到的结果（见上面 "3" + "3"）。
print(int("3") + 3)

# int 和 float 混在一起算，结果会自动变成 float，这叫类型提升。
# 你不用手动转，Python 会帮你，但你要知道结果类型变了。
print(3 + 3.0)


